export const getBrand = (slug) => brands.find((b) => b.slug === slug);

export const getCar = (carSlug) => {
  for (const b of brands) {
    const car = b.cars.find((c) => c.slug === carSlug);
    if (car) return { brand: b, car };
  }
  return null;
};

export const getAllCars = () => brands.flatMap((b) => b.cars.map((c) => ({ ...c, brand: b })));
